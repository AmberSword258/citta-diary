const years = Object.keys(CNY).map(Number).sort((a, b) => a - b);
const dn = (y, s) => Math.round(Date.UTC(y, Number(s.slice(0, 2)) - 1, Number(s.slice(3))) / 86400000);

const derived = {};
const wrong = [];
for (const y of years) {
  if (!CNY[y + 1]) continue;
  const len = dn(y + 1, CNY[y + 1]) - dn(y, CNY[y]);
  const months = Math.round(len / 29.530588861);
  const m = LEAP_INFO[y] || 0;
  if (months === 13) {
    if (m === 0) { wrong.push(`${y}: 应为闰年但闰月表为 0`); continue; }
    derived[y] = [m, 0]; // 天数稍后由朔日填充
  } else if (m !== 0) {
    wrong.push(`${y}: 非闰年但闰月表为 ${m}`);
  }
}

// 闰月天数：由「下表正月朔日 → 闰月位置」推算（用平均朔望月近似即可，稍后由 lunar.js 精修）
const L = require(path.join(__dirname, '..', 'src', 'shared', 'lunar.js'));
for (const y of Object.keys(derived).map(Number)) {
  const s1 = dn(y, CNY[y]);
  const s1Next = dn(y + 1, CNY[y + 1]);
  const count = Math.round((s1Next - s1) / 29.530588861);
  const starts = [s1];
  let cursor = s1;
  for (let i = 1; i < count; i++) {
    cursor = L.nextNewMoonDay(cursor);
    starts.push(cursor);
  }
  const leapPos = derived[y][0] + 1; // 1-based
  const st = starts[leapPos - 1];
  const en = leapPos < count ? starts[leapPos] : s1Next;
  derived[y] = [derived[y][0], en - st];
}

const out = { cny: CNY, leap: derived };

